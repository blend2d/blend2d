//! is utilized by \ref BLString, \ref BLArray, \ref BLBitArray, and other specialized containers.
//!
//! ### Views & Common Types
//!
//!   - \ref BLSpan<T> - non-owning view of a contiguous array or string
//!   - \ref BLStringView - non-owning view of string, essentially an alias of `BLSpan<const char>`
//!   - \ref BLRange - start/end range, which can be used with contiguous containers
//!
//! ### Sequential Containers
//!
//!   - \ref BLArray<T> - growable array of T elements. Can hold both primitive types and Blend2D objects
//!     - \ref BLArrayCore - C API type representing \ref BLArray<T>
//!
