//!   - \ref BLSize - 2D size composed of `[w, h]` values (64-bit floats)
//!   - \ref BLSizeI - 2D size composed of `[w, h]` values (32-bit integers)
//!   - \ref BLBox - 2D rectangular area composed of `[x0, y0, x1, y1]` values (64-bit floats)
